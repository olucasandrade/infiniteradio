import type {
  GenerationContext,
  MusicalEvent,
  SectionGenerator,
  StationDefinition,
} from '@infinite-radio/shared'
import {
  PROGRESSIONS,
  buildChord,
  chance,
  createEventFactory,
  createSectionRandom,
  densityForState,
  generateMelodyPhrase,
  applySwing,
  transposeProgression,
  voiceChord,
  voiceLead,
  type ChordSpec,
  type PhraseNote,
  type ScaleName,
} from '@infinite-radio/composition-engine'

import { param, sectionBeats, sectionFrom } from './shared'
import { planStationSet, setPhrase, setState } from './set-plan'

/**
 * Blue Notes — jazz and mellow fusion.
 *
 * Real harmony: predefined progression templates, extended voicings
 * voiced with voice leading from chord to chord, a swung ride pattern,
 * walking-ish bass, and melody phrases generated by the constrained
 * melody engine (never unrestricted random notes).
 */

const SCALE: ScaleName = 'dorian'
const KEY_TRANSPOSE = 10 // templates are in C; Bb is 10 semitones up
const CHORDS_PER_SECTION = 4
const CHORD_BEATS = 8 // one chord every 2 bars of the 8-bar section

/**
 * Effective key for this section: the episode's tonic and mode when a
 * transmission is steering the station, otherwise the house key of Bb
 * dorian. Templates are written in C, so the transpose equals the tonic
 * pitch class.
 */
function keyFor(context: GenerationContext): { rootPc: number; scale: ScaleName } {
  const episode = context.episode
  return {
    rootPc: episode?.keyRootPc ?? KEY_TRANSPOSE,
    scale: episode?.scale ?? SCALE,
  }
}

function progressionFor(
  parameters: Record<string, number>,
  rng: () => number,
  movement: number,
  rootPc: number,
): ChordSpec[] {
  // Episode movement nudges the harmonic ambition up or down.
  const complexity = param(parameters, 'harmonicComplexity') + (movement - 0.5) * 0.2
  let template
  if (complexity < 0.35) template = PROGRESSIONS.popTurnaround
  else if (complexity < 0.7) template = PROGRESSIONS.twoFiveOne
  else template = rng() < 0.5 ? PROGRESSIONS.modalDrift : PROGRESSIONS.openLift
  return transposeProgression(template, rootPc)
}

function colorChord(quality: ChordSpec['quality'], complexity: number): ChordSpec['quality'] {
  if (complexity < 0.33 && (quality === 'minor11' || quality === 'minor9')) return 'minor7'
  if (complexity > 0.63 && quality === 'minor7') return 'minor9'
  if (complexity > 0.63 && quality === 'major7') return 'major9'
  return quality
}

function chordRoots(progression: ChordSpec[], context: GenerationContext): ChordSpec[] {
  // Rotate the progression start per section for long-form variety.
  const rotation = setPhrase(context) % progression.length
  return [...progression.slice(rotation), ...progression.slice(0, rotation)]
}

/** Deterministic melody phrase for a section index (one level deep). */
function phraseFor(
  seed: number,
  sectionIndex: number,
  complexity: number,
  activity: number,
  chordSpec: ChordSpec,
  melodyRootMidi: number,
  scale: ScaleName,
): PhraseNote[] {
  const rng = createSectionRandom(seed, sectionIndex * 31 + 7)
  return generateMelodyPhrase({
    rng,
    keyRootMidi: melodyRootMidi,
    scale,
    chordRootMidi: 48 + chordSpec.rootPc,
    chordQuality: chordSpec.quality,
    phraseLengthBeats: CHORD_BEATS,
    noteCount: Math.max(2, Math.round(2 + activity * 6)),
    complexity: 0.3 + complexity * 0.5,
    registerMidi: 74,
    octaveSpan: 1,
  })
}

class BlueNotesGenerator implements SectionGenerator {
  generateSection(context: GenerationContext) {
    const rng = context.random
    const bars = context.bars
    const beats = sectionBeats(bars)
    const event = createEventFactory(`bn-${context.sectionIndex}`)
    const events: MusicalEvent[] = []

    const swingIntensity = param(context.parameters, 'swingIntensity')
    const melodicActivity = param(context.parameters, 'melodicActivity')
    const rhythmicDensity = param(context.parameters, 'rhythmicDensity')
    const harmonicComplexity = param(context.parameters, 'harmonicComplexity')

    const state = setState(context)
    const density = densityForState(state)

    const key = keyFor(context)
    const keyRootMidi = 36 + key.rootPc // bass register, Bb2 by default
    const melodyRootMidi = keyRootMidi + 12
    const movement = context.episode?.movement ?? 0.5

    const jazzForms = [PROGRESSIONS.twoFiveOne, PROGRESSIONS.modalDrift, PROGRESSIONS.openLift, PROGRESSIONS.popTurnaround]
    const progression = context.setPlan
      ? transposeProgression(jazzForms[context.setPlan.harmony]!, key.rootPc).map((chord) => ({
          ...chord,
          quality: colorChord(chord.quality, harmonicComplexity),
        }))
      : progressionFor(context.parameters, rng, movement, key.rootPc)
    const sectionChords = chordRoots(progression, context)

    const swing = (time: number) => applySwing(time, swingIntensity * (context.setPlan ? 0.56 + context.setPlan.groove * 0.11 : 0.9))

    // -- Harmony: voiced chords with voice leading across the progression.
    const voiced: number[][] = []
    for (let c = 0; c < CHORDS_PER_SECTION; c++) {
      const spec = sectionChords[c % sectionChords.length]!
      const chord = buildChord(48 + spec.rootPc, spec.quality)
      const previous = voiced.length > 0 ? voiced[voiced.length - 1]! : voiceChord(chord, 58, 4)
      voiced.push(voiceLead(previous, chord))
    }

    // -- Electric piano comping: offbeat stabs, denser with rhythmicDensity.
    if (density > 0.4) {
      const stabChance = 0.25 + rhythmicDensity * 0.5
      for (let c = 0; c < CHORDS_PER_SECTION; c++) {
        const chordStart = c * CHORD_BEATS
        const voicing = voiced[c]!
        for (let b = 0; b < CHORD_BEATS; b++) {
          // Offbeats (the "and"), with occasional downbeat anticipation.
          const onOffbeat = chance(rng, stabChance)
          const onDownbeat = b % 4 === 0 && chance(rng, stabChance * 0.35)
          if (!onOffbeat && !onDownbeat) continue
          const time = swing(chordStart + b + (onOffbeat && !onDownbeat ? 0.5 : 0))
          for (const tone of voicing) {
            events.push(
              event({
                type: 'note',
                instrument: 'electric-piano',
                time,
                duration: onDownbeat ? 1.4 : 0.9,
                pitch: tone,
                velocity: 0.45 + rng() * 0.25,
              }),
            )
          }
        }
      }
    }

    // -- Bass: root on one, fifth or approach on three; more motion with
    //    rhythmic density.
    if (density > 0.35) {
      for (let bar = 0; bar < bars; bar++) {
        const spec = sectionChords[Math.floor((bar * 4) / CHORD_BEATS) % sectionChords.length]!
        const root = 36 + spec.rootPc
        const fifth = root + 7
        const approach = chance(rng, 0.5) ? root + 10 : root + 12
        events.push(
          event({
            type: 'note',
            instrument: 'soft-bass',
            time: swing(bar * 4),
            duration: 1.8,
            pitch: root,
            velocity: 0.6 + rng() * 0.15,
          }),
        )
        if (rhythmicDensity > 0.3) {
          events.push(
            event({
              type: 'note',
              instrument: 'soft-bass',
              time: swing(bar * 4 + 1),
              duration: 0.85,
              pitch: root + (chance(rng, 0.5) ? 2 : 7),
              velocity: 0.4 + rng() * 0.12,
            }),
          )
          events.push(
            event({
              type: 'note',
              instrument: 'soft-bass',
              time: swing(bar * 4 + 2),
              duration: 1.6,
              pitch: chance(rng, 0.6) ? fifth : approach,
              velocity: 0.5 + rng() * 0.15,
            }),
          )
        }
        if (rhythmicDensity > 0.45 && chance(rng, 0.75)) {
          const nextSpec = sectionChords[Math.floor(((bar + 1) * 4) / CHORD_BEATS) % sectionChords.length]!
          const nextRoot = 36 + nextSpec.rootPc
          events.push(
            event({
              type: 'note',
              instrument: 'soft-bass',
              time: swing(bar * 4 + 3),
              duration: 0.75,
              pitch: nextRoot + (chance(rng, 0.5) ? 1 : -1),
              velocity: 0.4 + rng() * 0.1,
            }),
          )
        }
        if (rhythmicDensity > 0.7 && chance(rng, 0.6)) {
          events.push(
            event({
              type: 'note',
              instrument: 'soft-bass',
              time: swing(bar * 4 + 3.5),
              duration: 0.4,
              pitch: chance(rng, 0.5) ? root + 12 : approach,
              velocity: 0.42,
            }),
          )
        }
      }
    }

    // -- Ride: swung quarters + offbeat eighths, soft brush velocities.
    if (density > 0.45) {
      for (let beat = 0; beat < beats; beat++) {
        events.push(
          event({
            type: 'drum',
            instrument: 'hi-hat',
            time: swing(beat),
            duration: 0,
            velocity: beat % 4 === 2 ? 0.5 : 0.34,
          }),
        )
        if (chance(rng, 0.55 + rhythmicDensity * 0.3)) {
          events.push(
            event({
              type: 'drum',
              instrument: 'hi-hat',
              time: swing(beat + 0.5),
              duration: 0,
              velocity: 0.22 + rng() * 0.12,
            }),
          )
        }
      }
      for (let bar = 0; bar < bars; bar++) {
        for (const backbeat of [1, 3]) {
          events.push(
            event({
              type: 'drum',
              instrument: 'snare',
              time: swing(bar * 4 + backbeat),
              duration: 0,
              velocity: 0.16 + rhythmicDensity * 0.12,
              parameters: { age: 0.7 },
            }),
          )
        }
      }
      // Sparse kick on the downbeat of each 4-bar phrase.
      for (let bar = 0; bar < bars; bar += 4) {
        events.push(
          event({
            type: 'drum',
            instrument: 'kick',
            time: swing(bar * 4),
            duration: 0,
            velocity: 0.35,
          }),
        )
      }
    }

    // -- Melody: constrained phrases, quoting the previous section.
    if (melodicActivity > 0.2 && density > 0.5 && chance(rng, 0.4 + melodicActivity * 0.5)) {
      const phraseStart = ((setPhrase(context) + (context.setPlan?.groove ?? 0)) % 2) * CHORD_BEATS
      const leadChord = sectionChords[phraseStart / CHORD_BEATS]!
      const previousPhrase =
        context.sectionIndex > 0 && chance(rng, 0.4)
          ? phraseFor(
              context.seed,
              context.sectionIndex - 1,
              harmonicComplexity,
              melodicActivity,
              leadChord,
              melodyRootMidi,
              key.scale,
            )
          : undefined
      const phrase = generateMelodyPhrase({
        rng: context.setPlan ? createSectionRandom(context.seed, 37) : rng,
        keyRootMidi: melodyRootMidi,
        scale: key.scale,
        chordRootMidi: 48 + leadChord.rootPc,
        chordQuality: leadChord.quality,
        phraseLengthBeats: CHORD_BEATS,
        noteCount: Math.max(2, Math.round(2 + melodicActivity * 6)),
        complexity: 0.3 + harmonicComplexity * 0.5,
        previousPhrase,
        registerMidi: 74,
        octaveSpan: 1,
      })

      for (const note of phrase) {
        events.push(
          event({
            type: 'note',
            instrument: 'electric-piano',
            mixRole: 'lead',
            time: swing(phraseStart + note.time),
            duration: note.duration,
            pitch: note.pitch,
            velocity: note.velocity * 0.8,
          }),
        )
      }
    }

    if (!events.some((note) => note.type === 'note' && note.time < 4)) {
      for (const [index, pitch] of voiced[0]!.entries()) {
        events.push(event({
          type: 'note', instrument: 'electric-piano', time: index * 0.045,
          duration: 3.5, pitch, velocity: 0.43 - index * 0.035,
        }))
      }
    }

    const harmony = sectionChords
      .slice(0, CHORDS_PER_SECTION)
      .map((spec) => `${spec.rootPc}:${spec.quality}`)

    return sectionFrom(context, bars, events, {
      energy: 0.35 + rhythmicDensity * 0.3 + melodicActivity * 0.2,
      harmony,
    })
  }
}

