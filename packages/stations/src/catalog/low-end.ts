import type { TrackSeed } from './tracks'

function t(
  title: string,
  artist: string,
  year: number,
  keyRootPc: number,
  scale: TrackSeed['scale'],
  energy: number,
  brightness: number,
  movement: number,
  swing: number,
): TrackSeed {
  return {
    title,
    artist,
    year,
    keyRootPc,
    scale,
    energy,
    brightness,
    movement,
    swing,
    rhythmicDensity: movement,
    texture: 1 - brightness * 0.6,
  }
}

